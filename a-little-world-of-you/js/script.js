/* =============================================================================
   A LITTLE WORLD OF YOU - behaviour
   Vanilla JavaScript, no libraries. Reads its words and photos from js/content.js
   and the photo sizes from js/photo-manifest.js (generated by tools/optimize_images.py).

   Sections in this file:
     1. Helpers
     2. Rendering: welcome, gallery, letter
     3. Scroll reveal
     4. Lightbox (tap, buttons, keyboard, swipe)
     5. Music (prepared, inactive until configured)
     6. Start-up
   ============================================================================= */
(function () {
  'use strict';

  var C = window.SITE_CONTENT;
  var MANIFEST = window.PHOTO_MANIFEST || {};
  var IMAGE_DIR = 'assets/images/';

  var reducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)');

  /* ------------------------------------------------------------ 1. Helpers */

  function $(selector, root) { return (root || document).querySelector(selector); }

  function make(tag, className, text) {
    var node = document.createElement(tag);
    if (className) node.className = className;
    if (text != null) node.textContent = text;
    return node;
  }

  /* Puts text into a node. *asterisks* become <em> italics. Built with DOM nodes
     (never innerHTML), so nothing typed in content.js can inject markup. */
  function setRichText(node, text) {
    node.textContent = '';
    String(text || '').split(/(\*[^*]+\*)/).forEach(function (part) {
      if (!part) return;
      if (part.length > 2 && part.charAt(0) === '*' && part.charAt(part.length - 1) === '*') {
        node.appendChild(make('em', null, part.slice(1, -1)));
      } else {
        node.appendChild(document.createTextNode(part));
      }
    });
  }

  function plainText(text) { return String(text || '').replace(/\*/g, ''); }

  function setOptionalText(selector, text) {
    var node = $(selector);
    if (!node) return;
    if (text) { setRichText(node, text); node.hidden = false; } else { node.hidden = true; }
  }

  function scrollToSection(id) {
    var target = document.getElementById(id);
    if (!target) return;
    target.scrollIntoView({ behavior: reducedMotion.matches ? 'auto' : 'smooth', block: 'start' });
    var heading = $('h2', target);
    if (heading) heading.focus({ preventScroll: true });
  }

  function missingBlock(photoId) {
    return make('div', 'photo-missing',
      'Photo missing: ' + photoId + '. Put the original in source-photos/ and run tools/optimize_images.py.');
  }

  /* Builds a responsive <img> for a photo id. Returns null if the manifest has no entry. */
  function buildImage(photoId, alt, sizes, eager) {
    var info = MANIFEST[photoId];
    if (!info) return null;
    var img = document.createElement('img');
    img.alt = alt || '';
    img.width = info.w;            /* intrinsic size -> reserves space, no layout jump */
    img.height = info.h;
    img.decoding = 'async';
    img.loading = eager ? 'eager' : 'lazy';
    if (eager) img.setAttribute('fetchpriority', 'high');
    img.srcset = srcsetFor(photoId);
    img.sizes = sizes;
    var fallbackWidth = info.widths.filter(function (w) { return w <= 1080; }).pop() || info.widths[0];
    img.src = IMAGE_DIR + photoId + '-' + fallbackWidth + '.webp';
    return img;
  }

  function srcsetFor(photoId) {
    return MANIFEST[photoId].widths.map(function (w) {
      return IMAGE_DIR + photoId + '-' + w + '.webp ' + w + 'w';
    }).join(', ');
  }

  /* --------------------------------------------------------- 2. Rendering */

  function renderWelcome() {
    var W = C.welcome;
    setRichText($('#welcome-eyebrow'), W.eyebrow);
    setRichText($('#welcome-title'), W.name);
    setRichText($('#welcome-message'), W.message);
    $('#enter-btn').textContent = W.buttonLabel || 'Come in';

    var frame = $('#welcome-photo');
    var img = buildImage(W.photo.id, W.photo.alt, '(min-width: 30rem) 22rem, 80vw', true);
    if (img) {
      img.style.objectPosition = W.photo.position || '50% 30%';
      img.addEventListener('error', function () { frame.textContent = ''; frame.appendChild(missingBlock(W.photo.id)); });
      frame.appendChild(img);
    } else {
      frame.appendChild(missingBlock(W.photo.id));
    }
  }

  /* Returns the list of lightbox items (one per gallery photo). */
  function renderGallery() {
    var G = C.gallery;
    setRichText($('#gallery-eyebrow'), G.eyebrow);
    setRichText($('#gallery-title'), G.title);
    setOptionalText('#gallery-intro', G.intro);

    var list = $('#gallery-list');
    var items = [];

    G.photos.forEach(function (photo, index) {
      var size = photo.size === 'inset' ? 'inset' : 'full';
      var align = photo.align === 'left' || photo.align === 'right' ? photo.align : 'center';
      var classes = 'shot rs shot--' + size + ' shot--' + (size === 'inset' ? align : 'center') + (photo.mat ? ' shot--mat' : '');

      var figure = make('figure', classes);
      var item = { id: photo.id, alt: photo.alt || '', caption: photo.caption || '', missing: false, button: null };
      items.push(item);

      /* Image widths: full = page width minus margins; inset = 82% of that; two columns on tablets+ */
      var sizes = '(min-width: 48rem) 30rem, ' +
        (size === 'inset' ? 'calc((100vw - 2rem) * 0.82)' : 'calc(100vw - 2rem)');

      var img = buildImage(photo.id, photo.alt, sizes, false);

      function markMissing() {
        item.missing = true;
        figure.textContent = '';
        figure.appendChild(missingBlock(photo.id));
      }

      if (!img) {
        markMissing();
      } else {
        var button = make('button', 'shot__btn');
        button.type = 'button';
        button.setAttribute('aria-label', 'Enlarge photo: ' + plainText(photo.alt));
        item.button = button;
        img.addEventListener('error', markMissing);
        button.appendChild(img);
        figure.appendChild(button);
        button.addEventListener('click', function () { Lightbox.open(index, button); });
      }

      if (photo.caption && !item.missing) {
        var caption = make('figcaption');
        setRichText(caption, photo.caption);
        figure.appendChild(caption);
      }
      list.appendChild(figure);
    });

    return items;
  }

  function renderLetter() {
    var L = C.letter;
    setRichText($('#letter-eyebrow'), L.eyebrow);
    setRichText($('#letter-title'), L.title);
    setOptionalText('#letter-preface', L.preface);

    var body = $('#letter-body');
    if (L.salutation) {
      var salutation = make('p', 'letter__salutation rs');
      setRichText(salutation, L.salutation);
      body.appendChild(salutation);
    }
    (L.paragraphs || []).forEach(function (text) {
      var p = make('p', 'letter__p rs');
      setRichText(p, text);
      body.appendChild(p);
    });
    if (L.closing) {
      var closing = make('p', 'letter__closing rs');
      setRichText(closing, L.closing);
      body.appendChild(closing);
    }
    if (L.signature) {
      var signature = make('p', 'letter__signature rs');
      setRichText(signature, L.signature);
      body.appendChild(signature);
    }

    var back = $('#back-to-gallery');
    back.textContent = L.backToGalleryLabel || 'Back to the photos';
    back.addEventListener('click', function () { scrollToSection('gallery'); });
  }

  /* -------------------------------------------------------- 3. Scroll reveal */

  function initReveal() {
    var nodes = document.querySelectorAll('.rs');
    if (!('IntersectionObserver' in window) || reducedMotion.matches) {
      nodes.forEach(function (n) { n.classList.add('is-visible'); });
      return;
    }
    var observer = new IntersectionObserver(function (entries) {
      entries.forEach(function (entry) {
        if (entry.isIntersecting) {
          entry.target.classList.add('is-visible');
          observer.unobserve(entry.target);
        }
      });
    }, { rootMargin: '0px 0px -6% 0px', threshold: 0 });
    nodes.forEach(function (n) { observer.observe(n); });
  }

  /* ----------------------------------------------------------- 4. Lightbox */

  var Lightbox = (function () {
    var dialog, img, caption, count, stage;
    var items = [];
    var current = 0;
    var opener = null;
    var hasNativeDialog = false;

    function init(galleryItems) {
      items = galleryItems;
      dialog = $('#lightbox');
      img = $('#lightbox-img');
      caption = $('#lightbox-caption');
      count = $('#lightbox-count');
      stage = $('#lightbox-stage');
      hasNativeDialog = typeof dialog.showModal === 'function';

      $('#lightbox-close').addEventListener('click', close);
      $('#lightbox-prev').addEventListener('click', function () { step(-1); });
      $('#lightbox-next').addEventListener('click', function () { step(1); });

      /* Tap the dark area around the photo to close */
      dialog.addEventListener('click', function (e) {
        if (e.target === dialog || e.target === stage) close();
      });
      dialog.addEventListener('keydown', onKey);
      dialog.addEventListener('close', onClosed);      /* fires on Esc and on close() */
      dialog.addEventListener('cancel', function () {});/* native Esc handling is fine */

      initSwipe();
    }

    function validIndexes() {
      var out = [];
      items.forEach(function (it, i) { if (!it.missing) out.push(i); });
      return out;
    }

    function open(index, openerButton) {
      opener = openerButton || null;
      show(index);
      document.documentElement.classList.add('lightbox-open');
      if (hasNativeDialog) {
        if (!dialog.open) dialog.showModal();
      } else {
        dialog.setAttribute('open', '');
      }
      var closeBtn = $('#lightbox-close');
      if (closeBtn) closeBtn.focus();
    }

    function close() {
      if (hasNativeDialog) {
        if (dialog.open) dialog.close();
      } else {
        dialog.removeAttribute('open');
        onClosed();
      }
    }

    function onClosed() {
      document.documentElement.classList.remove('lightbox-open');
      if (opener && document.contains(opener)) opener.focus();   /* return focus to the photo you opened */
    }

    function show(index) {
      var it = items[index];
      if (!it || it.missing) return;
      current = index;
      img.alt = it.alt;
      img.sizes = '100vw';
      img.srcset = srcsetFor(it.id);
      var widths = MANIFEST[it.id].widths;
      img.src = IMAGE_DIR + it.id + '-' + widths[widths.length - 1] + '.webp';
      setRichText(caption, it.caption);

      var valid = validIndexes();
      count.textContent = 'Photo ' + (valid.indexOf(index) + 1) + ' of ' + valid.length;
      opener = it.button || opener;

      /* Warm the cache for the neighbours so swiping feels instant */
      [step.peek(-1), step.peek(1)].forEach(function (i) {
        if (i == null || i === index) return;
        var pre = new Image();
        var ws = MANIFEST[items[i].id].widths;
        pre.src = IMAGE_DIR + items[i].id + '-' + ws[Math.min(1, ws.length - 1)] + '.webp';
      });
    }

    function step(direction) {
      var valid = validIndexes();
      if (valid.length < 2) return;
      var pos = valid.indexOf(current);
      show(valid[(pos + direction + valid.length) % valid.length]);
    }
    step.peek = function (direction) {
      var valid = validIndexes();
      if (valid.length < 2) return null;
      var pos = valid.indexOf(current);
      return valid[(pos + direction + valid.length) % valid.length];
    };

    function onKey(e) {
      if (e.key === 'ArrowLeft') { e.preventDefault(); step(-1); }
      else if (e.key === 'ArrowRight') { e.preventDefault(); step(1); }
      else if (e.key === 'Escape' && !hasNativeDialog) { close(); }
    }

    /* Swipe left/right to move between photos (single finger, not while pinch-zoomed) */
    function initSwipe() {
      var startX = 0, startY = 0, tracking = false;
      stage.addEventListener('touchstart', function (e) {
        tracking = e.touches.length === 1 && !(window.visualViewport && window.visualViewport.scale > 1.02);
        if (tracking) { startX = e.touches[0].clientX; startY = e.touches[0].clientY; }
      }, { passive: true });
      stage.addEventListener('touchend', function (e) {
        if (!tracking || !e.changedTouches.length) return;
        tracking = false;
        var dx = e.changedTouches[0].clientX - startX;
        var dy = e.changedTouches[0].clientY - startY;
        if (Math.abs(dx) > 50 && Math.abs(dx) > Math.abs(dy) * 1.5) step(dx < 0 ? 1 : -1);
      }, { passive: true });
      stage.addEventListener('touchcancel', function () { tracking = false; }, { passive: true });
    }

    return { init: init, open: open, close: close };
  })();

  /* -------------------------------------------------------------- 5. Music */

  /* TODO: ADD BACKGROUND MUSIC HERE
     Music is configured in js/content.js (music.enabled and music.src).
     Nothing below runs unless music.enabled is true. */
  function initMusic() {
    var cfg = C.music || {};
    var button = $('#music-toggle');

    if (!cfg.enabled || !cfg.src) {
      button.hidden = true;
      return { start: function () {} };
    }

    var audio = new Audio();
    audio.preload = 'none';          /* the file is not downloaded until playback starts */
    audio.loop = true;
    audio.src = cfg.src;

    var targetVolume = typeof cfg.volume === 'number' ? Math.min(1, Math.max(0, cfg.volume)) : 0.35;
    var fadeMs = Math.max(0, (cfg.fadeInSeconds || 0) * 1000);
    var fadeTimer = null;
    var userPaused = false;
    var pausedByHide = false;

    function setUi(playing) {
      button.classList.toggle('is-playing', playing);
      button.setAttribute('aria-label', playing ? 'Pause music' : 'Play music');
    }

    function fadeTo(volume, ms, done) {
      clearInterval(fadeTimer);
      var from = audio.volume, started = Date.now();
      if (!ms) { audio.volume = volume; if (done) done(); return; }
      fadeTimer = setInterval(function () {
        var t = Math.min(1, (Date.now() - started) / ms);
        audio.volume = from + (volume - from) * t;
        if (t === 1) { clearInterval(fadeTimer); if (done) done(); }
      }, 50);
    }

    function play() {
      audio.volume = 0;
      var attempt = audio.play();
      if (attempt && attempt.then) {
        attempt.then(function () { setUi(true); fadeTo(targetVolume, fadeMs); })
               .catch(function () { setUi(false); });    /* blocked by the browser: stay silent */
      } else {
        setUi(true); fadeTo(targetVolume, fadeMs);
      }
    }

    function pause() {
      fadeTo(0, 250, function () { audio.pause(); });
      setUi(false);
    }

    /* If the file is missing or unreadable, quietly remove the button */
    audio.addEventListener('error', function () { button.hidden = true; });

    button.hidden = false;
    setUi(false);
    button.addEventListener('click', function () {
      if (audio.paused) { userPaused = false; play(); } else { userPaused = true; pause(); }
    });

    /* Be a good citizen: pause when the page is hidden, resume if the visitor had not paused */
    document.addEventListener('visibilitychange', function () {
      if (document.hidden && !audio.paused) { pausedByHide = true; audio.pause(); setUi(false); }
      else if (!document.hidden && pausedByHide && !userPaused) { pausedByHide = false; play(); }
    });

    return {
      /* Called from the welcome button (a real tap, so browsers allow sound) */
      start: function () { if (!userPaused && audio.paused) play(); }
    };
  }

  /* ---------------------------------------------------------- 6. Start-up */

  function start() {
    if (!C) {
      document.body.insertAdjacentHTML('afterbegin',
        '<p class="noscript">js/content.js could not be loaded. Check that the file exists.</p>');
      return;
    }
    document.title = C.siteTitle || document.title;

    renderWelcome();
    var galleryItems = renderGallery();
    renderLetter();

    Lightbox.init(galleryItems);
    var music = initMusic();

    $('#enter-btn').addEventListener('click', function () {
      music.start();
      scrollToSection('gallery');
    });

    initReveal();
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', start);
  } else {
    start();
  }
})();
